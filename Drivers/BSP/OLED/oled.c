// 函数声明
static uint32_t mypow(uint8_t m, uint8_t n);

// I2C 初始化
static void I2C_Init(void)
{
    hi2c1.Instance = I2C1;
    hi2c1.Init.ClockSpeed = 400000;
    hi2c1.Init.DutyCycle = I2C_DUTYCYCLE_2;
    hi2c1.Init.OwnAddress1 = 0;
    hi2c1.Init.AddressingMode = I2C_ADDRESSINGMODE_7BIT;
    hi2c1.Init.DualAddressMode = I2C_DUALADDRESS_DISABLE;
    hi2c1.Init.OwnAddress2 = 0;
    hi2c1.Init.GeneralCallMode = I2C_GENERALCALL_DISABLE;
    hi2c1.Init.NoStretchMode = I2C_NOSTRETCH_DISABLE;
    
    // 使能 I2C1 时钟
    __HAL_RCC_I2C1_CLK_ENABLE();
    __HAL_RCC_GPIOB_CLK_ENABLE();
    
    // 配置 PB6 和 PB7 为 I2C1 引脚
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = GPIO_PIN_6 | GPIO_PIN_7;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_OD;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);
    
    HAL_I2C_Init(&hi2c1);
}

// 向 OLED 写入一个字节
static void OLED_WriteByte(uint8_t dat, uint8_t cmd)
{
    uint8_t buf[2];
    buf[0] = cmd ? 0x40 : 0x00; // 0x00 命令模式，0x40 数据模式
    buf[1] = dat;
    
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, 100);
}

// 刷新 OLED 显示
static uint8_t refresh_enabled = 1;

void OLED_RefreshControl(uint8_t en)
{
    refresh_enabled = en;
    if (en) OLED_Refresh();
}

void OLED_Refresh(void)
{
    if (!refresh_enabled) return;
    uint8_t i, j;
    for(i = 0; i < 8; i++)
    {
        OLED_WriteByte(0xB0 + i, 0); // 设置页地址
        OLED_WriteByte(0x00, 0);     // 设置列地址低 4 位
        OLED_WriteByte(0x10, 0);     // 设置列地址高 4 位
        
        for(j = 0; j < 128; j++)
        {
            OLED_WriteByte(OLED_Gram[j][i], 1);
        }
    }
}

// 清屏
void OLED_Clear(void)
{
    uint8_t i, j;
    for(i = 0; i < 128; i++)
    {
        for(j = 0; j < 8; j++)
        {
            OLED_Gram[i][j] = 0x00;
        }
    }
    OLED_Refresh();
}

// 开启显示
void OLED_Display_On(void)
{
    OLED_WriteByte(0x8D, 0); // 电荷泵设置
    OLED_WriteByte(0x14, 0); // 开启电荷泵
    OLED_WriteByte(0xAF, 0); // 开启显示
}

// 关闭显示
void OLED_Display_Off(void)
{
    OLED_WriteByte(0x8D, 0); // 电荷泵设置
    OLED_WriteByte(0x10, 0); // 关闭电荷泵
    OLED_WriteByte(0xAE, 0); // 关闭显示
}

// 初始化 OLED
void OLED_Init(void)
{
    // 初始化 I2C
    I2C_Init();
    
    // 延时，确保 OLED 上电稳定
    HAL_Delay(100);
    
    //  OLED 初始化命令
    OLED_WriteByte(0xAE, 0); // 关闭显示
    OLED_WriteByte(0x00, 0); // 设置列地址低 4 位
    OLED_WriteByte(0x10, 0); // 设置列地址高 4 位
    OLED_WriteByte(0x40, 0); // 设置起始行
    OLED_WriteByte(0xB0, 0); // 设置页地址
    OLED_WriteByte(0x81, 0); // 设置对比度
    OLED_WriteByte(0xCF, 0); // 对比度值
    OLED_WriteByte(0xA1, 0); // 设置段重映射
    OLED_WriteByte(0xA6, 0); // 正常显示
    OLED_WriteByte(0xA8, 0); // 设置多路复用率
    OLED_WriteByte(0x3F, 0); // 1/64 占空比
    OLED_WriteByte(0xC8, 0); //  COM 扫描方向
    OLED_WriteByte(0xD3, 0); // 设置显示偏移
    OLED_WriteByte(0x00, 0); // 偏移 0
    OLED_WriteByte(0xD5, 0); // 设置时钟分频因子
    OLED_WriteByte(0x80, 0); // 分频因子
    OLED_WriteByte(0xD9, 0); // 设置预充电周期
    OLED_WriteByte(0xF1, 0); // 预充电周期
    OLED_WriteByte(0xDA, 0); // 设置 COM 硬件引脚配置
    OLED_WriteByte(0x12, 0); // 配置
    OLED_WriteByte(0xDB, 0); // 设置 VCOMH 电压倍率
    OLED_WriteByte(0x40, 0); // 倍率
    OLED_WriteByte(0x8D, 0); // 电荷泵设置
    OLED_WriteByte(0x14, 0); // 开启电荷泵
    OLED_WriteByte(0xAF, 0); // 开启显示
    
    // 清屏
    OLED_Clear();
}

// 显示一个字符（6x8）
void OLED_ShowChar(uint8_t x, uint8_t y, uint8_t chr)
{
    uint8_t c = 0, i = 0;
    c = chr - ' ';
    if (c > 64) c--;
    
    if(x > OLED_WIDTH - 6) {
        x = 0;
        y++;
    }
    
    for(i = 0; i < 6; i++) {
        OLED_Gram[x + i][y] = Font6x8[c][i];
    }
}

// 显示字符串（6x8，末尾统一刷新）
void OLED_ShowString(uint8_t x, uint8_t y, uint8_t *chr)
{
    while(*chr != '\0') {
        OLED_ShowChar(x, y, *chr);
        x += 6;
        if(x > OLED_WIDTH - 6) {
            x = 0;
            y++;
        }
        chr++;
    }
    OLED_Refresh();
}

// 快速显示字符串（写GRAM不刷新，末尾一次刷新）
void OLED_ShowString_Fast(uint8_t x, uint8_t y, uint8_t *chr)
{
    if (!chr) return;
    while(*chr != '\0') {
        uint8_t c = *chr - ' ';
        if (c > 64) c--;
        if(x > OLED_WIDTH - 6) { x = 0; y++; }
        for(uint8_t i = 0; i < 6; i++)
            OLED_Gram[x + i][y] = Font6x8[c][i];
        x += 6;
        chr++;
    }
    OLED_Refresh();
}

// 显示数字
void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    uint8_t t, temp;
    uint8_t enshow = 0;
    
    for(t = 0; t < len; t++) {
        temp = (num / mypow(10, len - t - 1)) % 10;
        if(enshow == 0 && t < len - 1) {
            if(temp == 0) {
                OLED_ShowChar(x + t * 6, y, ' ');
                continue;
            } else {
                enshow = 1;
            }
        }
        OLED_ShowChar(x + t * 6, y, temp + '0');
    }
}

// 绘制点
void OLED_DrawPoint(uint8_t x, uint8_t y, uint8_t t)
{
    uint8_t pos, bx, by;
    if(x > OLED_WIDTH - 1 || y > OLED_HEIGHT - 1) return;
    
    pos = y / 8;
    bx = x;
    by = y % 8;
    
    if(t) {
        OLED_Gram[bx][pos] |= (1 << by);
    } else {
        OLED_Gram[bx][pos] &= ~(1 << by);
    }
    
    OLED_Refresh();
}

// 绘制直线
void OLED_DrawLine(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2)
{
    int16_t dx, dy, sx, sy, err, e2;
    
    dx = x2 > x1 ? x2 - x1 : x1 - x2;
    dy = y2 > y1 ? y2 - y1 : y1 - y2;
    sx = x1 < x2 ? 1 : -1;
    sy = y1 < y2 ? 1 : -1;
    err = dx - dy;
    
    while(1) {
        OLED_DrawPoint(x1, y1, 1);
        if(x1 == x2 && y1 == y2) break;
        e2 = 2 * err;
        if(e2 > -dy) {
            err -= dy;
            x1 += sx;
        }
        if(e2 < dx) {
            err += dx;
            y1 += sy;
        }
    }
}

// 计算幂函数
static uint32_t mypow(uint8_t m, uint8_t n)
{
    uint32_t result = 1;
    while(n--) {
        result *= m;
    }
    return result;
}
